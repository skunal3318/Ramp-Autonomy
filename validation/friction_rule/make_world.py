#!/usr/bin/env python3
"""Generate a one-box-on-an-incline world for measuring the contact friction rule.

A rigid body on a slope slides when tan(angle) exceeds the effective
friction coefficient at the contact. That coefficient is derived by the
physics engine from BOTH surfaces, and the derivation is the thing under
test here: the box and the ramp are deliberately given different values,
so the angle at which the box lets go tells us which rule the engine used.

With BOX_MU 0.8 against RAMP_MU 0.5 the candidates separate cleanly:

    product          0.400   slides above 21.80 deg
    minimum          0.500   slides above 26.57 deg
    geometric mean   0.632   slides above 32.31 deg
    arithmetic mean  0.650   slides above 33.02 deg

Usage: make_world.py <angle_deg> <out.sdf>
"""
import math
import sys

RAMP_MU = 0.5
BOX_MU = 0.8
# Passing "default" for either mu omits that body's <surface> block
# entirely, which is how the robot's wheels are authored. That case is
# worth being able to measure rather than assume.
OMIT = 'default'
RAMP_LEN = 6.0
RAMP_WIDTH = 2.0
RAMP_THICK = 0.1
BOX_SIZE = 0.2
# Dropped from a hair above the surface rather than placed exactly on it,
# so an initial interpenetration cannot look like a slide.
SETTLE_GAP = 0.002

TEMPLATE = """<?xml version="1.0" ?>
<!--
  GENERATED by validation/friction_rule/make_world.py - do not edit by hand.

  Incline angle {angle_deg} deg. Ramp surface mu {ramp_mu}, box mu {box_mu}.
  A slide here means the engine's effective coefficient is below {tan:.4f}.
-->
<sdf version="1.9">
  <world name="friction_rule">

    <physics name="1ms" type="dart">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>

    <gravity>0 0 -9.81</gravity>

    <model name="incline">
      <static>true</static>
      <pose>0 0 0 0 {pitch_rad} 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{ramp_len} {ramp_width} {ramp_thick}</size></box></geometry>
          {ramp_surface}
        </collision>
        <visual name="visual">
          <geometry><box><size>{ramp_len} {ramp_width} {ramp_thick}</size></box></geometry>
        </visual>
      </link>
    </model>

    <model name="test_box">
      <pose>{box_x} 0 {box_z} 0 {pitch_rad} 0</pose>
      <link name="link">
        <inertial>
          <mass>1.0</mass>
          <inertia><ixx>{inertia}</ixx><iyy>{inertia}</iyy><izz>{inertia}</izz>
                   <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>
        </inertial>
        <collision name="collision">
          <geometry><box><size>{box_size} {box_size} {box_size}</size></box></geometry>
          {box_surface}
        </collision>
        <visual name="visual">
          <geometry><box><size>{box_size} {box_size} {box_size}</size></box></geometry>
        </visual>
      </link>
    </model>

  </world>
</sdf>
"""


def surface_block(mu):
    """A <surface> element, or nothing at all when mu is 'default'."""
    if mu == OMIT:
        return '<!-- no <surface>: inherits whatever the engine defaults to -->'
    return (f'<surface><friction><ode><mu>{mu}</mu>'
            f'<mu2>{mu}</mu2></ode></friction></surface>')


def main():
    if len(sys.argv) < 3:
        raise SystemExit(
            'usage: make_world.py <angle_deg> <out.sdf> [box_mu] [ramp_mu]\n'
            f'       either mu may be "{OMIT}" to omit that <surface> block')
    angle_deg = float(sys.argv[1])
    out_path = sys.argv[2]
    box_mu = sys.argv[3] if len(sys.argv) > 3 else BOX_MU
    ramp_mu = sys.argv[4] if len(sys.argv) > 4 else RAMP_MU

    pitch = math.radians(angle_deg)
    # Centre of a box resting on the incline's upper face, expressed in
    # world coordinates: the face sits at local z = ramp_thick/2, the box
    # centre a further box_size/2 above it, then rotated about Y by pitch.
    local_z = RAMP_THICK / 2.0 + BOX_SIZE / 2.0 + SETTLE_GAP
    box_x = local_z * math.sin(pitch)
    box_z = local_z * math.cos(pitch)

    with open(out_path, 'w') as f:
        f.write(TEMPLATE.format(
            angle_deg=angle_deg,
            pitch_rad=round(pitch, 6),
            tan=math.tan(pitch),
            ramp_mu=ramp_mu,
            box_mu=box_mu,
            ramp_surface=surface_block(ramp_mu),
            box_surface=surface_block(box_mu),
            ramp_len=RAMP_LEN,
            ramp_width=RAMP_WIDTH,
            ramp_thick=RAMP_THICK,
            box_size=BOX_SIZE,
            box_x=round(box_x, 6),
            box_z=round(box_z, 6),
            inertia=round(1.0 * (BOX_SIZE ** 2 + BOX_SIZE ** 2) / 12.0, 8),
        ))
    print(f'{out_path}: {angle_deg} deg, tan={math.tan(pitch):.4f}, '
          f'ramp mu={ramp_mu}, box mu={box_mu}')


if __name__ == '__main__':
    main()
