#!/usr/bin/env python3
"""Insert a reduced-friction patch partway down the ramp.

For issue #28. The existing low-friction worlds drop the friction of the
WHOLE ramp, which answers a different question: the robot never has good
traction in the first place, so a descent that goes badly says nothing
about whether the brake helped. What #28 needs is a robot that enters the
descent with normal traction, builds speed, and then meets a patch, so
the brake's intervention branch is actually provoked rather than simply
never reached.

The patch is derived from the base world's own ramp slab rather than
hardcoded, so it stays put if the ramp geometry is ever corrected again
(it has been once already, see validation/phase8/crest_freeze/).

Usage:
  make_patch_world.py <base_world.sdf> <out.sdf> [mu] [fraction] [length_m]

  mu        patch friction           (default 0.35)
  fraction  how far down the descent the patch starts, 0 at the crest and
            1 at the foot            (default 0.40)
  length_m  patch length along the slope, the robot is 0.80 m long
                                     (default 1.00)
"""
import math
import re
import sys

RAMP_MODEL = 'zone_b_ramp'
PATCH_THICKNESS = 0.01
DEFAULT_MU = 0.35
DEFAULT_FRACTION = 0.40
DEFAULT_LENGTH = 1.00

PATCH_MODEL = """
    <!-- GENERATED by validation/phase8/slip_patch/make_patch_world.py.
         Reduced-friction patch, mu {mu}, {length} m along the slope,
         starting {fraction:.0%} of the way down from the crest. The robot
         enters the descent on the ramp's normal {ramp_mu} and meets this
         under way. -->
    <model name="slip_patch">
      <static>true</static>
      <pose>{x} 0 {z} 0 {pitch} 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><box><size>{length} {width} {thickness}</size></box></geometry>
          <surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction></surface>
        </collision>
        <visual name="visual">
          <geometry><box><size>{length} {width} {thickness}</size></box></geometry>
          <material><ambient>0.15 0.15 0.18 1</ambient><diffuse>0.15 0.15 0.18 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


def ramp_geometry(sdf_text):
    """Pose, size and friction of the ramp slab, read from the base world."""
    model = re.search(
        r'<model name="%s">(.*?)</model>' % RAMP_MODEL, sdf_text, re.S)
    if not model:
        raise SystemExit(f'no <model name="{RAMP_MODEL}"> in the base world')
    body = model.group(1)

    pose = re.search(r'<pose>([^<]+)</pose>', body)
    size = re.search(r'<box><size>([^<]+)</size></box>', body)
    mu = re.search(r'<mu>([^<]+)</mu>', body)
    if not (pose and size and mu):
        raise SystemExit('ramp slab is missing a pose, size or friction value')

    px, py, pz, roll, pitch, yaw = [float(v) for v in pose.group(1).split()]
    sx, sy, sz = [float(v) for v in size.group(1).split()]
    return (px, pz, pitch), (sx, sy, sz), float(mu.group(1))


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__.strip().splitlines()[-6])
    base_path, out_path = sys.argv[1], sys.argv[2]
    mu = float(sys.argv[3]) if len(sys.argv) > 3 else DEFAULT_MU
    fraction = float(sys.argv[4]) if len(sys.argv) > 4 else DEFAULT_FRACTION
    length = float(sys.argv[5]) if len(sys.argv) > 5 else DEFAULT_LENGTH

    if not 0.0 <= fraction <= 1.0:
        raise SystemExit(f'fraction must be between 0 and 1, got {fraction}')

    sdf = open(base_path, encoding='utf-8').read()
    (cx, cz, pitch), (slab_len, slab_width, slab_thick), ramp_mu = ramp_geometry(sdf)

    if mu >= ramp_mu:
        raise SystemExit(
            f'patch mu {mu} is not below the ramp\'s own {ramp_mu}, '
            'so it would not reduce traction at all')

    # The ramp's local +x points uphill, so the crest is at +slab_len/2 and
    # the foot at -slab_len/2. Walk down from the crest by the requested
    # fraction and centre the patch there.
    along = slab_len / 2.0 - fraction * slab_len
    normal = slab_thick / 2.0 + PATCH_THICKNESS / 2.0

    # Rotate (along, normal) about Y by the slab's own pitch, then translate
    # onto the slab's centre. Same transform the slab itself carries.
    x = cx + along * math.cos(pitch) + normal * math.sin(pitch)
    z = cz - along * math.sin(pitch) + normal * math.cos(pitch)

    patch = PATCH_MODEL.format(
        mu=mu, ramp_mu=ramp_mu, fraction=fraction,
        x=round(x, 4), z=round(z, 4), pitch=pitch,
        length=length, width=round(slab_width, 4), thickness=PATCH_THICKNESS,
    )
    out = sdf.replace('</world>', patch + '\n  </world>')
    if out == sdf:
        raise SystemExit('could not find </world> to insert before')
    open(out_path, 'w', encoding='utf-8').write(out)

    print(f'{out_path}')
    print(f'  ramp      mu {ramp_mu}, {slab_len} m slope, pitch '
          f'{math.degrees(pitch):.1f} deg')
    print(f'  patch     mu {mu}, {length} m, {fraction:.0%} down from the crest')
    print(f'  placed at x={x:.3f} z={z:.3f}')
    print(f'  robot meets it after {fraction * slab_len:.2f} m of descent')


if __name__ == '__main__':
    main()
